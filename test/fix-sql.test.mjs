import { test } from 'node:test'
import assert from 'node:assert/strict'
import { buildFixSql, quoteIdent, quoteLiteral, splitPolicyObject } from '../src/fix-sql.mjs'

const NOW = new Date('2026-11-07T12:00:00Z')
const build = (findings, schema = 'public', extra = {}) =>
  buildFixSql({ schema, findings, ...extra }, { version: '9.9.9', now: NOW })

/** The executable part (between begin; and commit;), without comments. */
const body = (sql) =>
  sql.slice(sql.indexOf('begin;'), sql.indexOf('commit;')).split('\n').filter((l) => l && !l.startsWith('--') && l !== 'begin;')
/** The TODO part (after commit;). */
const todo = (sql) => sql.slice(sql.indexOf('commit;') + 7)

test('quoteIdent / quoteLiteral double the right quote and always quote', () => {
  assert.equal(quoteIdent('payments'), '"payments"')
  assert.equal(quoteIdent('Pay "Out"'), '"Pay ""Out"""')
  assert.equal(quoteIdent('My Table'), '"My Table"')
  assert.equal(quoteLiteral("ava'tars"), "'ava''tars'")
  assert.equal(quoteLiteral('a"b'), `'a"b'`)
})

test('splitPolicyObject keeps quotes inside the policy name', () => {
  assert.deepEqual(splitPolicyObject('notes."read all"'), { table: 'notes', policy: 'read all' })
  assert.deepEqual(splitPolicyObject('notes."say "hi" to all"'), { table: 'notes', policy: 'say "hi" to all' })
  assert.equal(splitPolicyObject('notes'), null)
})

test('header names the version and is wrapped in begin/commit', () => {
  const { sql } = build([])
  assert.match(sql, /generated by airlock-rls v9\.9\.9 on 2026-11-07/)
  assert.match(sql, /REVIEW BEFORE APPLYING/)
  assert.ok(sql.indexOf('begin;') < sql.indexOf('commit;'))
  assert.match(sql, /No mechanical fixes for this audit/)
})

test('each mechanical kind becomes exactly its statement, schema-qualified and quoted', () => {
  const findings = [
    { kind: 'rls_disabled', severity: 'fail', object: 'Pay "Out"', detail: 'x' },
    { kind: 'anon_executes_definer', severity: 'warn', object: 'fn:grant_credits', detail: 'x' },
    { kind: 'definer_search_path_mutable', severity: 'warn', object: 'fn:grant_credits', detail: 'x' },
    { kind: 'view_bypasses_rls', severity: 'warn', object: 'view:Open View', detail: 'x' },
    { kind: 'matview_exposed', severity: 'fail', object: "matview:It's a Dump", detail: 'x' },
    { kind: 'public_bucket', severity: 'warn', object: `storage:a "b'c"`, detail: 'x' },
    { kind: 'owner_bypasses_rls', severity: 'warn', object: 'table:owned', detail: 'x' },
  ]
  const { sql, statements } = build(findings, 'Fix Me')
  assert.equal(statements, 7)
  assert.deepEqual(body(sql), [
    'alter table "Fix Me"."Pay ""Out""" enable row level security;',
    'revoke execute on function "Fix Me"."grant_credits" from public, anon;',
    `alter function "Fix Me"."grant_credits" set search_path = '';`,
    'alter view "Fix Me"."Open View" set (security_invoker = true);',
    `revoke select on "Fix Me"."It's a Dump" from anon, authenticated;`,
    `update storage.buckets set public = false where id = 'a "b''c"';`,
    'alter table "Fix Me"."owned" force row level security;',
  ])
})

test('enabling RLS warns that it locks the table and ships a commented policy template', () => {
  const { sql, todos } = build([{ kind: 'rls_disabled', severity: 'fail', object: 'payments', detail: 'x' }])
  assert.match(sql, /LOCKS the table for the API/)
  assert.equal(todos, 1)
  assert.match(todo(sql), /^-- create policy "owner can read" on "public"\."payments"/m)
  assert.match(todo(sql), /<owner_column>/)
})

test('a permissive or unscoped policy is NEVER rewritten: only a commented template', () => {
  const kinds = ['permissive_true', 'anon_unscoped', 'authenticated_unscoped', 'or_branch_unscoped',
    'write_unscoped', 'write_unchecked', 'update_using_unscoped', 'delete_unscoped']
  for (const kind of kinds) {
    const { sql, statements, todos } = build([{ kind, severity: 'fail', object: 'notes."say "hi""', detail: '[UPDATE] x' }])
    assert.equal(statements, 0, kind)
    assert.equal(todos, 1, kind)
    assert.deepEqual(body(sql), [], kind)
    const t = todo(sql)
    // every template line is commented out
    for (const line of t.split('\n').filter(Boolean)) assert.ok(line.startsWith('--'), `${kind}: ${line}`)
    assert.match(t, /-- drop policy "say ""hi""" on "public"\."notes";/)
    assert.match(t, /for update to authenticated/)
  }
})

test('storage policy findings target storage.objects', () => {
  const { sql } = build([{ kind: 'storage_permissive_true', severity: 'fail', object: 'storage.objects."open"', detail: '[SELECT] x' }])
  assert.match(todo(sql), /-- drop policy "open" on storage\.objects;/)
})

test('decisions stay TODO: authenticated definer, realtime, bypassrls role, DAST leaks', () => {
  const { sql, statements, todos } = build([
    { kind: 'security_definer', severity: 'warn', object: 'fn:f', detail: 'x' },
    { kind: 'realtime_exposure', severity: 'warn', object: 'realtime:notes', detail: 'x' },
    { kind: 'bypassrls_role', severity: 'warn', object: 'role:svc "x"', detail: 'x' },
    { kind: 'anon_read_leak', severity: 'fail', object: 'notes', detail: 'x' },
    { kind: 'anon_write_leak', severity: 'fail', object: 'notes', detail: 'x' },
  ])
  assert.equal(statements, 0)
  assert.equal(todos, 5)
  const t = todo(sql)
  assert.match(t, /-- revoke execute on function "public"\."f" from public, anon, authenticated;/)
  assert.match(t, /-- alter publication supabase_realtime drop table "public"\."notes";/)
  assert.match(t, /-- alter role "svc ""x""" nobypassrls;/)
  assert.match(t, /-- revoke insert, update, delete on "public"\."notes" from anon;/)
})

test('allowed findings are never in the migration (they are not in result.findings)', () => {
  const { sql } = buildFixSql({
    schema: 'public',
    findings: [],
    allowed: [{ kind: 'rls_disabled', severity: 'fail', object: 'public_feed', detail: 'x' }],
  }, { version: '1', now: NOW })
  assert.ok(!sql.includes('public_feed'))
})

test('bookkeeping kinds produce nothing; duplicate statements collapse', () => {
  const { statements, todos } = build([
    { kind: 'allow_unused', severity: 'warn', object: 'x', detail: 'x' },
    { kind: 'scan_truncated', severity: 'warn', object: 'x', detail: 'x' },
    { kind: 'nothing_audited', severity: 'fail', object: 'public', detail: 'x' },
    { kind: 'owner_bypasses_rls', severity: 'warn', object: 'table:t', detail: 'x' },
    { kind: 'owner_bypasses_rls', severity: 'warn', object: 'table:t', detail: 'x' },
  ])
  assert.equal(statements, 1)
  assert.equal(todos, 0)
})

test('a name with a newline cannot break out of a comment', () => {
  const { sql } = build([{ kind: 'owner_bypasses_rls', severity: 'warn', object: 'table:evil\ndrop table x;', detail: 'x' }])
  // In the note it stays commented; in the statement it is inside the quoted identifier.
  assert.match(sql, /^-- drop table x;: the owner/m)
  assert.ok(sql.includes('alter table "public"."evil\ndrop table x;" force row level security;'))
  assert.ok(!sql.split('\n').some((l) => l === 'drop table x;'))
})
